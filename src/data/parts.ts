const curatedById = new Map(parts.map((p) => [p.id, p]));
let bookLookup: ((id: string) => Part | undefined) | null = null;

export function registerBookLookup(fn: (id: string) => Part | undefined) {
  bookLookup = fn;
}

export function partById(id: string) {
  return curatedById.get(id) ?? bookLookup?.(id);
}
