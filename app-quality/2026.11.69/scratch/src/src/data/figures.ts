/** Shared charts always match. Classic and Globetrotter drawings follow the selected coach. */
export function figureForCoach(id: string, coach: { family: string; alde: boolean }) {
  const side = classicOnly.has(id) ? "classic" : gtOnly.has(id) ? "gt" : "shared";
  if (side === "shared") return true;
  if (coach.family === "Classic" || coach.alde) return side === "classic";
  if (coach.family === "Globetrotter") return side === "gt";
  return false;
}

const FIGURE_BRANDS: Record<string, string[]> = {
  "fc-st": ["Suburban ST-65RL"],
  "fc-iw60": ["Suburban IW60"],
  "fc-aquago": ["Truma AquaGo"],
  "fc-combi": ["Truma Combi"],
  "fc-atwood-wh": ["Atwood tank"],
  "fc-furnace-sub": ["Suburban NT furnace"],
  "p96-1": ["Suburban ST-65RL", "Suburban IW60"],
};

/** Coach-side drawings, then the heater the fitment row actually names. */
export function figureApplies(id: string, model: Model, year?: number | null) {
  if (!figureForCoach(id, model)) return false;
  const brands = FIGURE_BRANDS[id];
  if (!brands || model.family === "Other") return true;
  const named = waterBrands(model, year);
  return brands.some((name) => named.has(name) || matrixAllows(name, model, year));
}

